#!/usr/bin/env python3
"""Render the C++ and PlatformIO views of config/boards/*.json; --check only reports drift."""
import argparse
import json
import sys

from board_config import ROOT, available, load


def identity_header(board):
    type_name = board.id.capitalize() + "Identity"
    return f"""// Generated by scripts/generate_board_config.py from config/boards/{board.id}.json. Do not edit.
#pragma once
#include <cstdint>

namespace openosc::board {{
struct {type_name} {{
    static constexpr const char *Name = "{board.name}";
    static constexpr const char *RecoveryProduct = "{board.name} Recovery";
    static constexpr const char *InstrumentProduct = "{board.name} Instruments";
    static constexpr const char *AboutText = "{board.name} / STM32H7B0";
    static constexpr uint32_t ImageBoardId = 0x{board.image_board_id:08X};
    static constexpr uint32_t FlashEnd = 0x{board.flash_end:08X};
}};
}} // namespace openosc::board
"""


def platformio_board(board):
    return json.dumps({
        "build": {"cpu": "cortex-m7", "f_cpu": "200000000L", "mcu": "stm32h7b0vbt6"},
        "frameworks": [],
        "name": f"OpenOSC {board.name}",
        "upload": {"maximum_ram_size": 130816, "maximum_size": 131072, "protocol": "custom"},
        "url": "https://github.com/STMicroelectronics/STM32CubeH7",
        "vendor": "OpenOSC",
    }, indent=2) + "\n"


def outputs():
    for board_id in available():
        board = load(board_id)
        yield ROOT / f"include/openosc/board/generated/{board.id}.hpp", identity_header(board)
        yield ROOT / f"boards/{board.id}.json", platformio_board(board)


def stale():
    return [path for path, text in outputs() if not path.exists() or path.read_text() != text]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        paths = stale()
        for path in paths:
            print(f"{path.relative_to(ROOT)} is out of date; run scripts/generate_board_config.py")
        sys.exit(1 if paths else 0)
    for path, text in outputs():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


if __name__ == "__main__":
    main()
